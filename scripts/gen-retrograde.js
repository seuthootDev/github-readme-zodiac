/**
 * Regenerate src/data/mercury-retrograde.js from an ephemeris (astronomy-engine, dev-only).
 * A period runs from the station retrograde to the station direct of Mercury's
 * geocentric ecliptic longitude, as UTC calendar dates.
 *
 * Usage: node scripts/gen-retrograde.js [fromYear] [toYear]
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as Astronomy from "astronomy-engine";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "../src/data/mercury-retrograde.js");

const from = Number(process.argv[2]) || 2026;
const to = Number(process.argv[3]) || 2035;

const DAY_MS = 86400000;
const lon = (ms) =>
  Astronomy.Ecliptic(Astronomy.GeoVector(Astronomy.Body.Mercury, new Date(ms), true)).elon;
/** Signed daily motion in degrees, unwrapped across 0°/360°. */
function motion(ms) {
  let d = lon(ms + DAY_MS / 2) - lon(ms - DAY_MS / 2);
  if (d > 180) d -= 360;
  if (d < -180) d += 360;
  return d;
}
/** Bisect to the minute where motion changes sign between a and b. */
function station(a, b) {
  const sa = Math.sign(motion(a));
  while (b - a > 60000) {
    const m = (a + b) / 2;
    if (Math.sign(motion(m)) === sa) a = m;
    else b = m;
  }
  return new Date((a + b) / 2);
}
const isoDate = (d) => d.toISOString().slice(0, 10);

const start = Date.UTC(from, 0, 1) - 40 * DAY_MS;
const end = Date.UTC(to + 1, 0, 1) + 40 * DAY_MS;
const periods = [];
let open = null;
let prev = motion(start);
for (let t = start + DAY_MS; t <= end; t += DAY_MS) {
  const cur = motion(t);
  if (prev > 0 && cur <= 0) open = station(t - DAY_MS, t);
  if (prev < 0 && cur >= 0 && open) {
    periods.push([isoDate(open), isoDate(station(t - DAY_MS, t))]);
    open = null;
  }
  prev = cur;
}
const kept = periods.filter(([s, e]) => Number(e.slice(0, 4)) >= from && Number(s.slice(0, 4)) <= to);

const body = kept.map(([s, e]) => `  ["${s}", "${e}"],`).join("\n");
writeFileSync(
  OUT,
  `/**
 * Mercury retrograde periods [station retrograde, station direct] as UTC dates, inclusive.
 * Generated by scripts/gen-retrograde.js (astronomy-engine) — do not edit by hand.
 */
export default [
${body}
];
`,
);
console.log(`Wrote ${kept.length} periods (${from}–${to}) to ${OUT}`);
